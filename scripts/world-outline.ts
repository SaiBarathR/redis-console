/**
 * Builds apps/web/src/assets/world-110m.ts, the land outline under the Workbench geo map, from Natural Earth's
 * 1:110m land polygons (public domain, https://www.naturalearthdata.com/about/terms-of-use/):
 *
 *   curl -fsSL -o /tmp/ne/ne_110m_land.geojson \
 *     https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_land.geojson
 *   node scripts/world-outline.ts /tmp/ne/ne_110m_land.geojson
 *
 * The outline is one SVG path in an equirectangular frame: x = longitude + 180, y = 90 - latitude, so the viewBox is
 * 0 0 360 180 and a point projects with the same formula. Coordinates are rounded to 0.1 degree (about 11 km), which is
 * finer than the 1:110m source. The map never fetches tiles at runtime (AGENTS.md hard rule 11).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

type Ring = [number, number][];
const source = process.argv[2];
if (!source) {
  console.error('usage: node scripts/world-outline.ts <ne_110m_land.geojson>');
  process.exit(64);
}
const geo = JSON.parse(readFileSync(source, 'utf8')) as {
  features: { geometry: { type: 'Polygon' | 'MultiPolygon'; coordinates: Ring[] | Ring[][] } }[];
};

const round = (n: number) => Math.round(n * 10);
const parts: string[] = [];
let points = 0;
for (const feature of geo.features) {
  const g = feature.geometry;
  const polygons = (g.type === 'Polygon' ? [g.coordinates] : g.coordinates) as Ring[][];
  for (const polygon of polygons) {
    for (const ring of polygon) {
      // Relative moves in tenths of a degree keep the path short; the module divides by 10 with a transform.
      let px = 0;
      let py = 0;
      let d = '';
      for (const [i, [lon, lat]] of ring.entries()) {
        const x = round(lon + 180);
        const y = round(90 - lat);
        if (i === 0) d += `M${x} ${y}`;
        else if (x !== px || y !== py) d += `l${x - px} ${y - py}`;
        else continue;
        px = x;
        py = y;
        points++;
      }
      parts.push(d + 'z');
    }
  }
}

const out = `/**
 * Land outline for the Workbench geo map, generated by scripts/world-outline.ts from Natural Earth 1:110m land
 * (public domain, https://www.naturalearthdata.com/about/terms-of-use/). Do not edit by hand.
 *
 * One SVG path in tenths of a degree, equirectangular: x = (longitude + 180) * 10, y = (90 - latitude) * 10.
 * ${points} points.
 */
export const WORLD_110M_PATH =
  ${JSON.stringify(parts.join(''))};
`;
const target = join(import.meta.dirname, '..', 'apps', 'web', 'src', 'assets', 'world-110m.ts');
writeFileSync(target, out);
console.log(`wrote ${target}: ${points} points, ${out.length} bytes`);
